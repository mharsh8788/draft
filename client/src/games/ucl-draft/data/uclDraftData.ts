function sanitizeClubSlug(club: string): string {
  return club.toLowerCase().replace(/\s+/g, '-').replace(/[^a-z0-9-]/g, '');
}

/**
 * 165 Unique 2020s Player-Season Cards across 15 clubs.
 * Normalized to adhere to the Player interface.
 */
export const UCL_PLAYER_SEASONS: Player[] = RAW_CARDS.map((card) => {
  const cardId = `${card.playerId}-${sanitizeClubSlug(card.club)}-${card.season}`;
  return {
    id: cardId,
    playerId: card.playerId,
    playerName: card.playerName,
    club: card.club,
    season: card.season,
    position: card.position,
    rating: card.rating,
    image: `/players/${card.playerId}.png`,

    // Compatibility fields
    name: card.playerName,
    shortName: card.shortName,
    nationality: card.nationality,
    countryCode: card.countryCode,
    primaryCategory: card.category,
    specificPosition: card.position,
    alternatePositions: card.eligiblePositions.filter((pos: any) => pos !== card.position),
    eligiblePositions: card.eligiblePositions,
    uclClubs: [card.club],
    primaryClub: card.club,
    era: card.season,
    editorialRating: card.rating,
    ratingRationale: `Provisional ${card.season} Champions League rating based on individual campaign performance.`,
    keyHighlight: `${card.club} ${card.season} Champions League Campaign`,
    shirtNumber: card.shirtNumber,
    uclStats: {
      titles: (card.club === 'Real Madrid' && card.season === '2021-22') ||
              (card.club === 'Chelsea' && card.season === '2020-21') ||
              (card.club === 'Manchester City' && card.season === '2022-23') ? 1 : 0,
      appearances: 10,
    },
  };
});

/**
 * Normalize club name for robust matching (e.g. 'PSG' vs 'Paris Saint-Germain').
 */
function normalizeClubName(club: string): string {
  const c = club.trim().toLowerCase();
  if (c === 'psg' || c === 'paris saint-germain') return 'psg';
  if (c === 'atletico madrid' || c === 'atlético madrid') return 'atletico madrid';
  return c;
}

/**
 * Fetch all cards for a specific club + season challenge.
 * Returns exactly 11 player-season cards.
 */
export function getCardsForChallenge(club: string, season: string = '2026-27'): Player[] {
  if (season === '2026-27') {
    const cards2026 = get2026_27CardsForClub(club);
    if (cards2026.length > 0) return cards2026;
  }
  const normClub = normalizeClubName(club);
  const exact = UCL_PLAYER_SEASONS.filter(
    (card) => normalizeClubName(card.club) === normClub && card.season === season
  );
  if (exact.length > 0) return exact;
  return UCL_PLAYER_SEASONS.filter((card) => normalizeClubName(card.club) === normClub);
}

/**
 * Randomly rolls an eligible Club + Season Challenge.
 */
export function getRandomClubSeasonChallenge(current?: { club: string; season: string }): ClubSeasonChallenge {
  return getRandom2026_27Challenge(current?.club);
}

/**
 * Check if a real player (by stable playerId) is already drafted in the XI.
 * Enforces rule: A real player can be selected only once in the same XI,
 * even if their cards appear in multiple clubs/seasons.
 */
export function isRealPlayerDrafted(squad: Record<string, Player | null>, playerId: string): boolean {
  return Object.values(squad).some((p) => p !== null && (p.playerId === playerId || p.id === playerId));
}
