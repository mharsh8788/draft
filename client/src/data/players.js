export const isPositionEligible = (player, targetPosition) => {
  if (!player || !targetPosition) return false;

  const playerPositions = [
    player.position,
    ...(Array.isArray(player.secondaryPositions) ? player.secondaryPositions : [])
  ].filter(Boolean);

  if (playerPositions.includes(targetPosition)) return true;

  switch (targetPosition) {
    case 'CM/CDM':
      return playerPositions.some(p => ['CM', 'CDM'].includes(p));

    case 'CAM/CM':
      return playerPositions.some(p => ['CAM', 'CM'].includes(p));

    case 'LW/CAM':
      return playerPositions.some(p => ['LW', 'CAM'].includes(p));

    case 'RW/CAM':
      return playerPositions.some(p => ['RW', 'CAM'].includes(p));

    case 'LM/LWB':
      return playerPositions.some(p => ['LM', 'LWB', 'LW', 'LB'].includes(p));

    case 'RM/RWB':
      return playerPositions.some(p => ['RM', 'RWB', 'RW', 'RB'].includes(p));

    case 'CAM/SS':
      return playerPositions.some(p => ['CAM', 'SS', 'CF', 'ST'].includes(p));

    case 'LM':
      return playerPositions.some(p => ['LM', 'LW'].includes(p));

    case 'RM':
      return playerPositions.some(p => ['RM', 'RW'].includes(p));

    case 'LWB':
      return playerPositions.some(p => ['LWB', 'LB'].includes(p));

    case 'RWB':
      return playerPositions.some(p => ['RWB', 'RB'].includes(p));

    case 'ST':
      return playerPositions.some(p => ['ST', 'CF'].includes(p));

    default:
      return playerPositions.includes(targetPosition);
  }
};
